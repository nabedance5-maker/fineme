export const PREFECTURES = Object.keys(JAPAN_CITIES);

// 都市名から座標を取得
export function getCityCoords(prefecture, cityName) {
  const cities = JAPAN_CITIES[prefecture] || [];
  const found = cities.find(c => c.name === cityName || cityName.startsWith(c.name) || c.name.startsWith(cityName));
  return found ? { lat: found.lat, lon: found.lon } : null;
}
