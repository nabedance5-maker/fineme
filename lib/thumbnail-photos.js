export function unsplashUrl(id, opts = '') {
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop${opts}`;
}

export function slugHash(s) {
  return Math.abs([...s].reduce((h, c) => (Math.imul(31, h) + c.charCodeAt(0)) | 0, 0));
}

// category/axis 名から候補プールを1枚選ぶ（シード文字列で記事ごとに変える＝金太郎飴防止）
// track='belle' の場合はBelle（女性向け）専用プールのみを使う。EXTRA_PHOTOSはFineme（男性向け）の
// 補完プールなので、Belle記事には混ぜない（男性の写真が女性向け記事に紛れ込むのを防ぐ）。
export function pickThumbnailPhoto(category, seedStr, track = 'fineme') {
  const isBelle = track === 'belle';
  const pool = [...new Set(
    isBelle
      ? [...(BELLE_PHOTOS[category] || []), ...BELLE_DEFAULT_PHOTOS]
      : [...(UNSPLASH_PHOTOS[category] || []), ...DEFAULT_PHOTOS, ...EXTRA_PHOTOS]
  )].filter(id => !/\s/.test(id));
  if (pool.length === 0) return (isBelle ? BELLE_DEFAULT_PHOTOS : DEFAULT_PHOTOS)[0];
  const seed = slugHash(seedStr || category || '');
  return pool[seed % pool.length];
}
