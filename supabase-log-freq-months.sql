-- ✅ 本番適用済 2026-07-26
-- New Me Log の頻度に「月」単位を追加する。
--
-- 背景：美容室は「4週ごと」より「月1回」で考える人が多い（でお指摘 2026-07-26）。
-- 単に表示を変えるだけでは足りない：
--   ・4週=28日なので、月1のつもりでも年間で1ヶ月ぶんズレる
--   ・費用も「月1回 ¥7,000」なら月額はちょうど ¥7,000 であるべきなのに、
--     4週換算だと 4.345/4 倍されて ¥7,604 になり直感に反する
-- そのため計算そのものを月基準にできるようにする。
--
-- frequency_weeks（既存・週数）と frequency_months（新規・月数）は排他的に使う。
-- 両方 null なら軸の推奨頻度を使う。既存データは frequency_weeks のままで動く。

ALTER TABLE user_service_logs ADD COLUMN IF NOT EXISTS frequency_months INTEGER;
